// anyEvents erases the param types of a mixed batch. sesamy.AnyEvent exists precisely
// because a direct conversion to sesamy.Event[any] does not compile.
func anyEvents(in ...sesamy.AnyEvent) []sesamy.Event[any] {
	out := make([]sesamy.Event[any], len(in))
	for i, e := range in {
		out[i] = e.AnyEvent()
	}

	return out
}

// Journey is the behaviour this package exists to model: a persona lands on the
// department, looks across both rails — trousers, then dresses — and comes back to the
// department, to the occasion it dresses for, ranked by its taste across both rails.
// From there it views and buys what it opened, goes back to the top of the department,
// and moves on to home decoration before it leaves: the department, the category of what
// it picks there, and a view — and ends on the listing of all products, the shop's whole
// ranking for this shopper, without opening anything more.
//
// Every listing but that last one is followed by a select_item carrying the same list
// id: the shopper opens what it chooses there (see Persona.Choose) — something it likes
// from the first few positions, not always the first, and not always its favourite.
// The categories are only where products are offered. What the shop — and any consumer
// of the traffic — learns from is what the shopper does in them: the product it opens
// in each, the one it views, the one it buys.
//
// Two tastes are at work. The persona's decides what the shopper picks; the shop never
// sees it. Every listing is ranked by the shopper's personalization vector instead, which
// the affinity corpus emits from the shopper's events so far — so a Journey's first
// listing, with no events yet, is in catalog order, the section is ranked by three picks,
// and the closing look at the department by everything the visit has shown.
//
// Nothing here is hardcoded per persona. The occasion comes from the persona's strongest
// occasion dimension and the product from its highest affinity score, so the behaviour in
// the payload is generated by the vector — change a persona and its journey follows.
func Journey(p Persona, opts ...Option) Session {
	s := newShopper(opts...)
	visit(p, s, true)

	return s.session(opts...)
}

// BrowseJourney takes the same route across the rails, views what it opened and leaves
// without adding anything. Funnel analysis is only meaningful against traffic that does
// not always convert.
func BrowseJourney(p Persona, opts ...Option) Session {
	s := newShopper(opts...)
	visit(p, s, false)

	return s.session(opts...)
}

// shopper is one shopper as the shop sees them: the affinity corpus their events go into
// as they happen, the envelope of the request in progress — its time moves on with every
// event — and the visit's events so far, each with when it was sent and the engagement
// time since the one before.
type shopper struct {
	corpus  *affinity.Corpus
	env     affinity.Envelope
	events  []sesamy.AnyEvent
	sent    []time.Time
	engaged []time.Duration
}

// newShopper is a shopper with no history, about to start a visit at the time and with
// the session id opts resolve to.
func newShopper(opts ...Option) *shopper {
	s := &shopper{corpus: affinity.New(nil)}
	s.start(NewContext(opts...))

	return s
}

// start begins a visit: no events yet, the clock at the visit's start.
func (s *shopper) start(c Context) {
	s.env = affinity.Envelope{At: time.UnixMicro(c.TimestampMicros).UTC(), Session: c.SessionID, Personalization: true}
	s.events, s.sent, s.engaged = nil, nil, nil
}

// emit sends events of the visit, one request each: the clock moves on by the time the
// shopper takes after the previous event, and the event goes into the shopper's corpus
// at that time straight away, so the next listing is ranked with it.
func (s *shopper) emit(events ...sesamy.AnyEvent) {
	for _, e := range events {
		engaged := firstEngagement
		if n := len(s.events); n > 0 {
			engaged = gap(s.events[n-1].AnyEvent().Name, s.env.Session+"#"+strconv.Itoa(n))
			s.env.At = s.env.At.Add(engaged)
		}

		s.events, s.sent, s.engaged = append(s.events, e), append(s.sent, s.env.At), append(s.engaged, engaged)
		s.corpus.Add(s.env, e.AnyEvent())
	}
}

// session is the visit so far as the client sent it: one request per event, each stamped
// with when it was sent and its engagement time, all under the visit's session id.
func (s *shopper) session(opts ...Option) Session {
	out := make(Session, 0, len(s.events))
	for i, e := range s.events {
		hit := append(slices.Clone(opts), WithTimestamp(s.sent[i]), WithSessionID(s.env.Session), WithEngagementTime(s.engaged[i]))
		out = append(out, Payload(anyEvents(e), hit...))
	}

	return out
}

// profile is what the shop ranks the next listing with: the personalization vector the
// corpus emits for the shopper now, and how many events went into it.
func (s *shopper) profile() Profile {
	return Profile{Taste: s.corpus.Derive(affinity.DefaultFade.Vector), Signals: s.corpus.Len()}
}

// stop is one listing on the route: the filter as the shop ranked it, and what the
// shopper opened from it.
type stop struct {
	Filter Filter
	Pick   Item
}

// route is the way every visit browses: the department, the trousers, the dresses, and
// back to the department narrowed to the persona's occasion. Each listing is ranked by
// the shopper's vector as it stands when the shopper gets there, and the shopper opens
// what it chooses from it — which goes into the corpus before the next listing.
func route(p Persona, s *shopper) []stop {
	out := make([]stop, 0, 4)

	for _, f := range []Filter{CategoryFilter, TrousersFilter, DressesFilter, SectionFilter(p)} {
		f = f.Personalize(s.profile())
		pick := choose(p, f)
		out = append(out, stop{Filter: f, Pick: pick})
		s.emit(ViewItemList(f), SelectItem(f, pick))
	}

	return out
}

// choose is what the shopper opens from a listing as the shop ranked it: Persona.Choose,
// seeded by the listing and by how much the shop knew when it ranked it — so the same
// listing on a later visit, ranked differently, can go differently too.
func choose(p Persona, f Filter) Item {
	return p.Choose(f.Apply(Catalog()), f.ListID()+"?"+f.Query()+"#"+strconv.Itoa(f.Profile.Signals))
}

// visit is one session: the route, then a view of what the shopper opened from its
// section and, if it converts, the cart — then back to the top of the department, ranked
// by everything the shop knows by then, to open something once more — on into home
// decoration — and last a look at the top-level listing of all products, where the visit
// ends without another click.
func visit(p Persona, s *shopper, convert bool) {
	stops := route(p, s)

	pick := stops[len(stops)-1].Pick
	s.emit(ViewItem(pick))

	if convert {
		s.emit(AddToCart(pick))
	}

	// the closing look at the department: how the shop ranks it after this visit
	closing := CategoryFilter.Personalize(s.profile())
	s.emit(ViewItemList(closing), SelectItem(closing, choose(p, closing)))

	// and on into home decoration: the department, ranked by what carries over from
	// fashion through the dimensions the two share, then the category of the shopper's
	// pick there, ranked with that pick learned, and a view of it
	home := HomeFilter.Personalize(s.profile())
	homePick := choose(p, home)
	s.emit(ViewItemList(home), SelectItem(home, homePick))

	rail := Filter{Category: homePick.Category(), Sort: SortAffinity}.Personalize(s.profile())
	homePick = choose(p, rail)
	s.emit(ViewItemList(rail), SelectItem(rail, homePick), ViewItem(homePick))

	// and last, the top of the tree: every product the shop sells, ranked by everything
	// it knows — the shop's whole view of this shopper, across both departments. The
	// visit ends here, on the listing: nothing more is opened.
	s.emit(ViewItemList(AllProductsFilter.Personalize(s.profile())))
}

// Day is a calendar day, the unit visit schedules are written in.
const Day = 24 * time.Hour

// Visit is one session in a shopper's history: whose taste drives it, how long before
// BaseTime it started, and whether it ends in the cart.
//
// The persona is per visit rather than per history so that taste can drift: a shopper
// who spends the first half of the month hunting for a gala dress and the second half
// back in office wear is two personas on one client id. Who the shopper is on the wire
// is the envelope's business, set through the options History takes.
type Visit struct {
	Persona Persona
	Ago     time.Duration
	Convert bool
}

// Month is a month of visits for one persona, ending at BaseTime: mostly browsing, with
// two conversions, visits getting more frequent towards the end as a returning shopper's
// do. The schedule is fixed so that fixtures built from it do not churn.
func Month(p Persona) []Visit {
	return []Visit{
		{Persona: p, Ago: 27 * Day},
		{Persona: p, Ago: 20 * Day},
		{Persona: p, Ago: 14 * Day, Convert: true},
		{Persona: p, Ago: 9 * Day},
		{Persona: p, Ago: 5 * Day},
		{Persona: p, Ago: 2 * Day},
		{Persona: p, Convert: true},
	}
}

// History replays visits as one Session each, oldest first, which is the order a
// pipeline expects them in. A visit starts at its scheduled time and gets that time, in
// unix seconds, as its session id — the way GA4 derives one; its requests follow at the
// pace the shopper takes. Time and session id are set after opts, so an option cannot
// break the schedule.
//
// The visits are one shopper's, so the shopper's corpus carries over: the first visit
// starts neutral and every later one is ranked by the vector of everything before it,
// whichever persona happened to be shopping.
func History(visits []Visit, opts ...Option) []Session {
	ordered := slices.Clone(visits)
	slices.SortStableFunc(ordered, func(a, b Visit) int { return cmp.Compare(b.Ago, a.Ago) })

	out := make([]Session, 0, len(ordered))
	s := newShopper()

	for _, v := range ordered {
		at := BaseTime.Add(-v.Ago)
		session := strconv.FormatInt(at.Unix(), 10)
		visitOpts := append(slices.Clone(opts), WithTimestamp(at), WithSessionID(session))

		s.start(NewContext(visitOpts...))
		visit(v.Persona, s, v.Convert)
		out = append(out, s.session(opts...))
	}

	return out
}
