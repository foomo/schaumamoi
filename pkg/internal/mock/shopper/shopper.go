// SectionFilter is the persona's occasion across the whole department, dresses and
// trousers together: the facet the shopper narrows to. How it is ranked is the shop's
// business, set with Personalize.
func SectionFilter(p persona.Persona) shop.Filter {
	return shop.Filter{Category: catalog.CategoryWomensFashion, Occasion: p.Occasion(), Sort: shop.SortAffinity}
}

// anyEvents erases the param types of a mixed batch. sesamy.AnyEvent exists precisely
// because a direct conversion to sesamy.Event[any] does not compile.
func anyEvents(in ...sesamy.AnyEvent) []sesamy.Event[any] {
	out := make([]sesamy.Event[any], len(in))
	for i, e := range in {
		out[i] = e.AnyEvent()
	}

	return out
}

// Journey is the behaviour the mock shop exists to model: a persona lands on the
// department, looks across both rails — trousers, then dresses — and comes back to the
// department, to the occasion it dresses for, ranked by its taste across both rails.
// From there it views and buys what it opened, goes back to the top of the department,
// and moves on to home decoration before it leaves: the department, the category of what
// it picks there, and a view — and ends on the listing of all products, the shop's whole
// ranking for this shopper, without opening anything more.
//
// Every listing but that last one is followed by a select_item carrying the same list
// id: the shopper opens what it chooses there (see Persona.Choose) — something it likes
// from the first few positions, not always the first, and not always its favourite.
// The categories are only where products are offered. What the shop — and any consumer
// of the traffic — learns from is what the shopper does in them: the product it opens
// in each, the one it views, the one it buys.
//
// Two tastes are at work. The persona's decides what the shopper picks; the shop never
// sees it. Every listing is ranked by the shopper's personalization vector instead, which
// the affinity still distills from the shopper's events so far — so a Journey's first
// listing, with no events yet, is in catalog order, the section is ranked by three picks,
// and the closing look at the department by everything the visit has shown.
//
// Nothing here is hardcoded per persona. The occasion comes from the persona's strongest
// occasion dimension and the product from its highest affinity score, so the behaviour in
// the payload is generated by the vector — change a persona and its journey follows.
func Journey(p persona.Persona, opts ...wire.Option) wire.Session {
	s := newShopper(opts...)
	visit(p, s, true)

	return s.session(opts...)
}

// BrowseJourney takes the same route across the rails, views what it opened and leaves
// without adding anything. Funnel analysis is only meaningful against traffic that does
// not always convert.
func BrowseJourney(p persona.Persona, opts ...wire.Option) wire.Session {
	s := newShopper(opts...)
	visit(p, s, false)

	return s.session(opts...)
}

// shopper is one shopper as the shop sees them: the affinity still their events go into
// as they happen, the visit's session and clock — the clock moves on with every event —
// and the visit's events so far, each with when it was sent and the engagement time
// since the one before.
type shopper struct {
	still     *affinity.Still
	sessionID string
	at        time.Time
	events    []sesamy.AnyEvent
	sent      []time.Time
	engaged   []time.Duration
}

// newShopper is a shopper with no history, about to start a visit at the time and with
// the session id opts resolve to.
func newShopper(opts ...wire.Option) *shopper {
	s := &shopper{still: affinity.New(nil)}
	s.start(wire.NewContext(opts...))

	return s
}

// start begins a visit: no events yet, the clock at the visit's start.
func (s *shopper) start(c wire.Context) {
	s.sessionID, s.at = c.SessionID, time.UnixMicro(c.TimestampMicros).UTC()
	s.events, s.sent, s.engaged = nil, nil, nil
}

// emit sends events of the visit, one request each: the clock moves on by the time the
// shopper takes after the previous event, and the event goes into the shopper's still
// at that time straight away, so the next listing is ranked with it.
func (s *shopper) emit(events ...sesamy.AnyEvent) {
	for _, e := range events {
		engaged := firstEngagement
		if n := len(s.events); n > 0 {
			engaged = gap(s.events[n-1].AnyEvent().Name, s.sessionID+"#"+strconv.Itoa(n))
			s.at = s.at.Add(engaged)
		}

		s.events, s.sent, s.engaged = append(s.events, e), append(s.sent, s.at), append(s.engaged, engaged)

		// the request as the client sends it, consented: what the shop learns from
		s.still.Feed(affinity.Envelope{TimestampMicros: s.at.UnixMicro(), SessionID: s.sessionID, Consent: wire.ConsentGranted()}, e.AnyEvent())
	}
}

// session is the visit so far as the client sent it: one request per event, each stamped
// with when it was sent and its engagement time, all under the visit's session id.
func (s *shopper) session(opts ...wire.Option) wire.Session {
	out := make(wire.Session, 0, len(s.events))
	for i, e := range s.events {
		hit := append(slices.Clone(opts), wire.WithTimestamp(s.sent[i]), wire.WithSessionID(s.sessionID), wire.WithEngagementTime(s.engaged[i]))
		out = append(out, wire.Payload(anyEvents(e), hit...))
	}

	return out
}

// profile is what the shop ranks the next listing with: the personalization vector the
// still distills for the shopper now, and how many events went into it.
func (s *shopper) profile() shop.Profile {
	return shop.Profile{Taste: s.still.Distill(affinity.DefaultFade.Vector), Signals: s.still.Len()}
}

// stop is one listing on the route: the filter as the shop ranked it, and what the
// shopper opened from it.
type stop struct {
	Filter shop.Filter
	Pick   catalog.Item
}

// route is the way every visit browses: the department, the trousers, the dresses, and
// back to the department narrowed to the persona's occasion. Each listing is ranked by
// the shopper's vector as it stands when the shopper gets there, and the shopper opens
// what it chooses from it — which goes into the still before the next listing.
func route(p persona.Persona, s *shopper) []stop {
	out := make([]stop, 0, 4)

	for _, f := range []shop.Filter{shop.CategoryFilter, shop.TrousersFilter, shop.DressesFilter, SectionFilter(p)} {
		f = f.Personalize(s.profile())
		pick := choose(p, f)
		out = append(out, stop{Filter: f, Pick: pick})
		s.emit(shop.ViewItemList(f), shop.SelectItem(f, pick))
	}

	return out
}

// choose is what the shopper opens from a listing as the shop ranked it: Persona.Choose,
// seeded by the listing and by how much the shop knew when it ranked it — so the same
// listing on a later visit, ranked differently, can go differently too.
func choose(p persona.Persona, f shop.Filter) catalog.Item {
	return p.Choose(f.Apply(catalog.All()), f.ListID()+"?"+f.Query()+"#"+strconv.Itoa(f.Profile.Signals))
}

// visit is one session: the route, then a view of what the shopper opened from its
// section and, if it converts, the cart — then back to the top of the department, ranked
// by everything the shop knows by then, to open something once more — on into home
// decoration — and last a look at the top-level listing of all products, where the visit
// ends without another click.
func visit(p persona.Persona, s *shopper, convert bool) {
	stops := route(p, s)

	pick := stops[len(stops)-1].Pick
	s.emit(shop.ViewItem(pick))

	if convert {
		s.emit(shop.AddToCart(pick))
	}

	// the closing look at the department: how the shop ranks it after this visit
	closing := shop.CategoryFilter.Personalize(s.profile())
	s.emit(shop.ViewItemList(closing), shop.SelectItem(closing, choose(p, closing)))

	// and on into home decoration: the department, ranked by what carries over from
	// fashion through the dimensions the two share, then the category of the shopper's
	// pick there, ranked with that pick learned, and a view of it
	home := shop.HomeFilter.Personalize(s.profile())
	homePick := choose(p, home)
	s.emit(shop.ViewItemList(home), shop.SelectItem(home, homePick))

	rail := shop.Filter{Category: homePick.Category(), Sort: shop.SortAffinity}.Personalize(s.profile())
	homePick = choose(p, rail)
	s.emit(shop.ViewItemList(rail), shop.SelectItem(rail, homePick), shop.ViewItem(homePick))

	// and last, the top of the tree: every product the shop sells, ranked by everything
	// it knows — the shop's whole view of this shopper, across both departments. The
	// visit ends here, on the listing: nothing more is opened.
	s.emit(shop.ViewItemList(shop.AllProductsFilter.Personalize(s.profile())))
}

// FirstSection is the persona's section as its first visit reaches it: narrowed to its
// occasion and ranked by what the shop learned from the three listings before.
func FirstSection(p persona.Persona) shop.Filter {
	stops := route(p, newShopper())

	return stops[len(stops)-1].Filter
}
