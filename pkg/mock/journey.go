package mock

import (
	"github.com/foomo/sesamy-go/pkg/encoding/mpv2"
	"github.com/foomo/sesamy-go/pkg/sesamy"
)

// anyEvents erases the param types of a mixed batch. sesamy.AnyEvent exists precisely
// because a direct conversion to sesamy.Event[any] does not compile.
func anyEvents(in ...sesamy.AnyEvent) []sesamy.Event[any] {
	out := make([]sesamy.Event[any], len(in))
	for i, e := range in {
		out[i] = e.AnyEvent()
	}

	return out
}

// Journey is the behaviour this package exists to model: a persona browses the dresses,
// narrows to the occasion it dresses for, has the listing re-ranked by its taste, then
// opens and buys its best match.
//
// Nothing here is hardcoded per persona. The occasion comes from the persona's strongest
// occasion dimension and the dress from its highest affinity score, so the behaviour in
// the payload is generated by the vector — change a persona and its journey follows.
func Journey(p Persona, opts ...Option) mpv2.Payload[any] {
	personalized := PersonalizedFilter(p)
	pick := p.TopMatch(personalized.Apply(Catalog()))

	return Payload(anyEvents(
		ViewItemList(CategoryFilter),
		ViewItemList(Filter{Category: CategoryDresses, Occasion: p.Occasion()}),
		ViewItemList(personalized),
		SelectItem(personalized, pick),
		ViewItem(pick),
		AddToCart(pick),
	), opts...)
}

// BrowseJourney browses and leaves without adding anything. Funnel analysis is only
// meaningful against traffic that does not always convert.
func BrowseJourney(p Persona, opts ...Option) mpv2.Payload[any] {
	personalized := PersonalizedFilter(p)

	return Payload(anyEvents(
		ViewItemList(CategoryFilter),
		ViewItemList(personalized),
		ViewItem(p.TopMatch(personalized.Apply(Catalog()))),
	), opts...)
}
