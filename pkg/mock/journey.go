// anyEvents erases the param types of a mixed batch. sesamy.AnyEvent exists precisely
// because a direct conversion to sesamy.Event[any] does not compile.
func anyEvents(in ...sesamy.AnyEvent) []sesamy.Event[any] {
	out := make([]sesamy.Event[any], len(in))
	for i, e := range in {
		out[i] = e.AnyEvent()
	}

	return out
}

// Journey is the behaviour this package exists to model: a persona lands on the
// department, looks across both rails — trousers, then dresses — and comes back to the
// department, to the occasion it dresses for, ranked by its taste across both rails.
// From there it views and buys what it opened, goes back to the top of the department,
// and moves on to home decoration before it leaves: the department, the category of what
// it picks there, and a view — and ends on the listing of all products, the shop's whole
// ranking for this shopper, without opening anything more.
//
// Every listing but that last one is followed by a select_item carrying the same list
// id: the shopper opens what it chooses there (see Persona.Choose) — something it likes
// from the first few positions, not always the first, and not always its favourite.
// The categories are only where products are offered. What the shop — and any consumer
// of the traffic — learns from is what the shopper does in them: the product it opens
// in each, the one it views, the one it buys.
//
// Two tastes are at work. The persona's decides what the shopper picks; the shop never
// sees it. Every listing is ranked by the shop's Profile instead, which a Journey starts
// neutral and which learns from each pick as the visit goes on — so the first listing is
// in catalog order, the section is ranked by three picks, and the closing look at the
// department by everything the visit taught the shop.
//
// Nothing here is hardcoded per persona. The occasion comes from the persona's strongest
// occasion dimension and the product from its highest affinity score, so the behaviour in
// the payload is generated by the vector — change a persona and its journey follows.
func Journey(p Persona, opts ...Option) mpv2.Payload[any] {
	events, _ := visit(p, Profile{}, true)

	return Payload(anyEvents(events...), opts...)
}

// BrowseJourney takes the same route across the rails, views what it opened and leaves
// without adding anything. Funnel analysis is only meaningful against traffic that does
// not always convert.
func BrowseJourney(p Persona, opts ...Option) mpv2.Payload[any] {
	events, _ := visit(p, Profile{}, false)

	return Payload(anyEvents(events...), opts...)
}

// stop is one listing on the route: the filter as the shop ranked it, and what the
// shopper opened from it.
type stop struct {
	Filter Filter
	Pick   Item
}

// route is the way every visit browses: the department, the trousers, the dresses, and
// back to the department narrowed to the persona's occasion. Each listing is ranked by
// the profile as it stands when the shopper gets there, and the shopper opens what it
// chooses from it — which the shop then learns from. It returns the stops and the
// profile after the last pick.
func route(p Persona, prof Profile) ([]stop, Profile) {
	out := make([]stop, 0, 4)

	for _, f := range []Filter{CategoryFilter, TrousersFilter, DressesFilter, SectionFilter(p)} {
		f = f.Personalize(prof)
		pick := choose(p, f)
		out = append(out, stop{Filter: f, Pick: pick})
		prof = prof.Learn(LearnSelect, pick)
	}

	return out, prof
}

// choose is what the shopper opens from a listing as the shop ranked it: Persona.Choose,
// seeded by the listing and by how much the shop knew when it ranked it — so the same
// listing on a later visit, ranked differently, can go differently too.
func choose(p Persona, f Filter) Item {
	return p.Choose(f.Apply(Catalog()), f.ListID()+"?"+f.Query()+"#"+strconv.Itoa(f.Profile.Signals))
}

// visit is one session: the route, then a view of what the shopper opened from its
// section and, if it converts, the cart — then back to the top of the department, ranked
// by everything the shop has learned by then, to open something once more — on into home
// decoration — and last a look at the top-level listing of all products, where the visit
// ends without another click. It starts from what the shop knew and returns what it knows
// after.
func visit(p Persona, prof Profile, convert bool) ([]sesamy.AnyEvent, Profile) {
	stops, prof := route(p, prof)

	out := make([]sesamy.AnyEvent, 0, 2*len(stops)+4)
	for _, s := range stops {
		out = append(out, ViewItemList(s.Filter), SelectItem(s.Filter, s.Pick))
	}

	pick := stops[len(stops)-1].Pick
	out = append(out, ViewItem(pick))
	prof = prof.Learn(LearnView, pick)

	if convert {
		out = append(out, AddToCart(pick))
		prof = prof.Learn(LearnCart, pick)
	}

	// the closing look at the department: how the shop ranks it after this visit
	closing := CategoryFilter.Personalize(prof)
	last := choose(p, closing)
	out = append(out, ViewItemList(closing), SelectItem(closing, last))
	prof = prof.Learn(LearnSelect, last)

	// and on into home decoration: the department, ranked by what carries over from
	// fashion through the dimensions the two share, then the category of the shopper's
	// pick there, ranked with that pick learned, and a view of it
	home := HomeFilter.Personalize(prof)
	homePick := choose(p, home)
	out = append(out, ViewItemList(home), SelectItem(home, homePick))
	prof = prof.Learn(LearnSelect, homePick)

	rail := Filter{Category: homePick.Category(), Sort: SortAffinity}.Personalize(prof)
	homePick = choose(p, rail)
	out = append(out, ViewItemList(rail), SelectItem(rail, homePick), ViewItem(homePick))
	prof = prof.Learn(LearnSelect, homePick).Learn(LearnView, homePick)

	// and last, the top of the tree: every product the shop sells, ranked by everything
	// it has learned — the shop's whole view of this shopper, across both departments.
	// The visit ends here, on the listing: nothing more is opened.
	out = append(out, ViewItemList(AllProductsFilter.Personalize(prof)))

	return out, prof
}

// Day is a calendar day, the unit visit schedules are written in.
const Day = 24 * time.Hour

// Visit is one session in a shopper's history: whose taste drives it, how long before
// BaseTime it started, and whether it ends in the cart.
//
// The persona is per visit rather than per history so that taste can drift: a shopper
// who spends the first half of the month hunting for a gala dress and the second half
// back in office wear is two personas on one client id. Who the shopper is on the wire
// is the envelope's business, set through the options History takes.
type Visit struct {
	Persona Persona
	Ago     time.Duration
	Convert bool
}

// Month is a month of visits for one persona, ending at BaseTime: mostly browsing, with
// two conversions, visits getting more frequent towards the end as a returning shopper's
// do. The schedule is fixed so that fixtures built from it do not churn.
func Month(p Persona) []Visit {
	return []Visit{
		{Persona: p, Ago: 27 * Day},
		{Persona: p, Ago: 20 * Day},
		{Persona: p, Ago: 14 * Day, Convert: true},
		{Persona: p, Ago: 9 * Day},
		{Persona: p, Ago: 5 * Day},
		{Persona: p, Ago: 2 * Day},
		{Persona: p, Convert: true},
	}
}

// History replays visits as one payload per session, oldest first, which is the order a
// pipeline expects them in. Each payload is stamped with the time its session started
// and gets that time, in unix seconds, as its session id — the way GA4 derives one.
// Those two are set after opts, so an option cannot break the schedule.
//
// The visits are one shopper's, so the shop's Profile carries over: the first visit
// starts neutral and every later one is ranked by everything learned before it,
// whichever persona happened to be shopping.
func History(visits []Visit, opts ...Option) []mpv2.Payload[any] {
	ordered := slices.Clone(visits)
	slices.SortStableFunc(ordered, func(a, b Visit) int { return cmp.Compare(b.Ago, a.Ago) })

	out := make([]mpv2.Payload[any], 0, len(ordered))
	prof := Profile{}

	for _, v := range ordered {
		at := BaseTime.Add(-v.Ago)
		visitOpts := append(slices.Clone(opts), WithTimestamp(at), WithSessionID(strconv.FormatInt(at.Unix(), 10)))

		var events []sesamy.AnyEvent
		events, prof = visit(v.Persona, prof, v.Convert)
		out = append(out, Payload(anyEvents(events...), visitOpts...))
	}

	return out
}
